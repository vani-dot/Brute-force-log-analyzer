@app.route("/api/live/stream")
def live_stream():
    """Server-Sent Events: findings pushed to the browser as they happen."""
    if not watcher:
        return jsonify({"error": "not running"}), 404

    active = watcher

    def events():
        listener = active.subscribe()
        try:
            yield f"data: {json.dumps({'type': 'state', 'data': active.status()})}\n\n"
            while True:
                try:
                    message = listener.get(timeout=15)
                    yield f"data: {json.dumps(message)}\n\n"
                except queue.Empty:
                    # A comment frame keeps proxies from closing an idle
                    # connection, and tells the browser we are still here.
                    yield ": keepalive\n\n"
        finally:
            active.unsubscribe(listener)

    return Response(events(), mimetype="text/event-stream", headers={
        "Cache-Control": "no-cache",
        "X-Accel-Buffering": "no",
        "Connection": "keep-alive",
    })


