@app.route("/api/lookup", methods=["POST"])
def lookup():
    """Look one address up with the methods the operator explicitly chose.

    Nothing is sent off this machine unless "online" is among them.
    """
    form = request.get_json(silent=True) or {}
    ip_text = str(form.get("ip", "")).strip()
    if not ip_text:
        return jsonify({"error": "No address supplied."}), 400

    methods = form.get("methods") or ["builtin"]
    if isinstance(methods, str):
        methods = [methods]
    return jsonify(enricher.investigate(ip_text, methods))


