# report.py
# ONE JOB: turn an AnalysisResult into a standalone HTML report.
#
# Standalone means exactly that: one file, no stylesheet, no script, no font
# and no image fetched from anywhere. It opens from a USB stick on a machine
# with no network, prints to PDF from any browser, and can be attached to a
# ticket without shipping a folder of assets alongside it.
#
# Every figure comes from the AnalysisResult. Nothing is hardcoded, and where
# a value is unknown the report says unknown rather than filling a gap.

