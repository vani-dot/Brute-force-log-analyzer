@app.route("/api/analyze", methods=["POST"])
def analyze():
    # Two ways in: a JSON body with pasted text, or a multipart file upload.
    if request.files.get("logfile"):
        upload = request.files["logfile"]
        source = upload.filename or "uploaded file"
        text = upload.read().decode("utf-8", errors="replace")
        form = request.form
    else:
        form = request.get_json(silent=True) or {}
        sample = form.get("sample")
        if sample:
            text = read_sample(sample)
            if text is None:
                return jsonify({"error": f"unknown sample: {sample}"}), 404
            source = sample
        else:
            text = form.get("text", "")
            source = "pasted input"

    if not text.strip():
        return jsonify({"error": "No log text supplied."}), 400

    geo = str(form.get("geo_lookup", "false")).lower() in ("1", "true", "on")
    result = detector_from(form).analyze_text(text, source=source)
    payload = build_payload(result, persist_mode="batch", geo_lookup=geo)
    payload["source_kind"] = source_kind_for(form.get("sample") or source)
    payload["provenance"] = (DATA_PROVENANCE
                             if payload["source_kind"] == "sample" else "")

    # Batch analysis alerts too, so a cron job driving /api/analyze behaves
    # the same as the live watcher.
    if str(form.get("alert", "false")).lower() in ("1", "true", "on"):
        payload["alerts"] = {
            f.key: [r.to_dict() for r in dispatcher.dispatch(
                f, {"source": source, "mode": "batch"})]
            for f in result.findings}

    return jsonify(payload)


