# ---- helpers -------------------------------------------------------------

def clamp(name, value, fallback):
    low, high = LIMITS[name]
    try:
        number = int(value)
    except (TypeError, ValueError):
        return fallback
    return max(low, min(high, number))


def sample_path(name):
    # Membership test against a set built from the filesystem, never a path
    # join on user input. "logs/attacks/x.log" is only served if that exact
    # string was produced by our own directory listing, so "../.." can never
    # match however it is encoded.
    if name in SAMPLE_NAMES:
        return os.path.join(BASE_DIR, name)
    if name == GENERATED_NAME:
        path = os.path.join(BASE_DIR, GENERATED_NAME)
        return path if os.path.exists(path) else None
    if name in {entry["name"] for entry in bundled_logs()}:
        return os.path.join(BASE_DIR, *name.split("/"))
    return None


def source_kind_for(name):
    """Which provenance note applies to this input."""
    if name == GENERATED_NAME:
        return "generated"
    if name in SAMPLE_NAMES or name.startswith("logs/"):
        return "sample"
    return "upload"


def read_sample(name):
    path = sample_path(name)
    if path is None:
        return None
    with open(path, errors="replace") as f:
        return f.read()


def allowlist_from(form):
    """Allowlist entries from the request, falling back to the environment."""
    raw = form.get("allowlist")
    if raw is None:
        return list(config.allowlist)
    if isinstance(raw, str):
        raw = raw.replace("\n", ",").split(",")
    return [str(entry).strip() for entry in raw if str(entry).strip()]


def detector_from(form):
    return BruteForceDetector(
        threshold=clamp("threshold", form.get("threshold"), DEFAULT_THRESHOLD),
        window=clamp("window", form.get("window"), DEFAULT_WINDOW),
        compromise_window=clamp("compromise_window",
                                form.get("compromise_window"),
                                COMPROMISE_WINDOW),
        min_failures=clamp("min_failures", form.get("min_failures"),
                           MIN_FAILURES_FOR_COMPROMISE),
        detect_compromise=str(form.get("detect_compromise", "true")).lower()
        not in ("false", "0", "off"),
        allowlist=allowlist_from(form),
    )


def build_payload(result, persist_mode=None, geo_lookup=False):
    """AnalysisResult -> the JSON the browser renders, with enrichment.

    geo_lookup=True additionally asks an online geolocation service where each
    routable attacking address is. That sends those addresses to a third
    party, so it is off unless the operator asks for it, and only routable
    addresses are ever sent.
    """
    payload = result.to_dict()
    enrichment = enricher.enrich_findings(result.findings)

    if geo_lookup:
        for key, record in enrichment.items():
            if not record.get("routable"):
                continue
            found = enricher.investigate(key, ["builtin", "maxmind", "online"])
            record.update(found["merged"])
            online = found["methods"].get("online", {})
            record["geo_source"] = "online" if online.get("ok") else ""
            if online.get("error"):
                record["geo_error"] = online["error"]

    for entry in payload["findings"]:
        record = enrichment.get(entry["key"])
        if record:
            entry["enrichment"] = record
            entry["location"] = Enricher.describe(record)
        if storage is not None:
            history = storage.history_for(entry["key"])
            # times_seen counts prior sightings, so subtract nothing yet —
            # this run has not been recorded at the point we read it.
            entry["times_seen"] = history["times_seen"] if history else 0

    for offender in payload["top_offenders"]:
        record = enricher.lookup(offender["ip"])
        offender["location"] = Enricher.describe(record)
        offender["kind"] = record.get("kind")

    if storage is not None and persist_mode:
        payload["run_id"] = storage.record_run(result, mode=persist_mode,
                                               enrichment=enrichment)
        payload["history"] = storage.summary()

    return payload


