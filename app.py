@app.route("/api/report", methods=["POST"])
def report():
    """Build a standalone HTML report for one analysis."""
    form = request.get_json(silent=True) or {}
    sample = form.get("sample")

    if sample:
        text = read_sample(sample)
        if text is None:
            return jsonify({"error": f"unknown sample: {sample}"}), 404
        source = sample
    else:
        text = form.get("text", "")
        source = form.get("source") or "pasted input"

    if not text.strip():
        return jsonify({"error": "No log text supplied."}), 400

    result = detector_from(form).analyze_text(text, source=source)

    history = {}
    if storage is not None:
        for finding in result.findings:
            record = storage.history_for(finding.key)
            if record:
                history[finding.key] = record

    if str(form.get("geo_lookup", "false")).lower() in ("1", "true", "on"):
        for finding in result.findings:
            if finding.pivot == "ip":
                enricher.investigate(finding.key,
                                     ["builtin", "maxmind", "online"])

    html = build_report(result, source_kind=source_kind_for(sample or source),
                        enricher=enricher, history=history)
    filename = (os.path.basename(str(source)).replace(" ", "_") or "report")
    return Response(html, mimetype="text/html", headers={
        "Content-Disposition":
            f'attachment; filename="bfla-report-{filename}.html"',
    })


@app.route("/api/samples")
def list_samples():
    """Sample cards, with stats computed by analysing each file right now.

    Deliberately not a stored description. If a sample file changes, the card
    changes with it, and a card can never claim something the tool does not
    actually produce.
    """
    detector = BruteForceDetector(allowlist=config.allowlist)
    catalogue = ([dict(s, group="examples") for s in EXAMPLE_LOGS]
                 + [dict(s, group="quick") for s in SAMPLES]
                 + [{"name": GENERATED_NAME, "label": "Generated log",
                     "group": "generated"}]
                 + bundled_logs())

    out = []
    for sample in catalogue:
        path = sample_path(sample["name"])
        if path is None:
            continue
        result = detector.analyze_file(path)
        stats = result.to_dict()["stats"]
        out.append({
            "name": sample["name"],
            "label": sample["label"],
            "group": sample.get("group", "quick"),
            "lines": stats["events"] + stats["skipped"],
            "events": stats["events"],
            "skipped": stats["skipped"],
            "findings": stats["findings"],
            "high": stats["high"],
            "size_bytes": os.path.getsize(path),
        })
    return jsonify({"provenance": DATA_PROVENANCE, "samples": out})


