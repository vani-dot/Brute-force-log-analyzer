# app.py
# The web front end. Owns HTTP concerns only — it parses nothing and detects
# nothing itself. It hands text to LogParser/BruteForceDetector and turns the
# AnalysisResult into JSON, exactly like the CLI turns it into text.
#
#   pip install -r requirements.txt
#   python app.py            -> http://127.0.0.1:5000
#
# Every number this serves is computed at request time. Nothing is canned:
# the sample cards report the analysis of the file as it is on disk right now,
# the history panel reports what SQLite actually holds, and the capability
# panel reports which integrations are genuinely configured.

