def esc(value):
    return html.escape(str(value if value is not None else ""))


class ReportBuilder:
    """Builds one self-contained HTML report from an AnalysisResult."""

    def __init__(self, result, source_kind="upload", generated_at=None,
                 enricher=None, history=None, tool_version="1.0"):
        self.result = result
        self.source_kind = source_kind
        self.generated_at = generated_at or datetime.now()
        self.enricher = enricher or Enricher()
        self.history = history or {}
        self.tool_version = tool_version

    # ---- narrative -------------------------------------------------

    def verdict(self):
        """One sentence a manager can act on, and the class of the box."""
        high = self.result.high_findings
        findings = self.result.findings
        if high:
            keys = ", ".join(sorted({f.key for f in high}))
            return ("breach", "Confirmed compromise",
                    f"{len(high)} source(s) authenticated successfully after "
                    f"repeated failures: {keys}. Treat the affected accounts "
                    f"as compromised — rotate credentials and review what was "
                    f"done in those sessions.")
        if findings:
            return ("attempts", "Attack attempts, no confirmed breach",
                    f"{len(findings)} finding(s) crossed the threshold of "
                    f"{self.result.threshold} failures in "
                    f"{self.result.window}s. Nothing in this log shows a "
                    f"successful login following those failures.")
        return ("clear", "No threats detected",
                f"Nothing in this log crossed {self.result.threshold} failures "
                f"within {self.result.window}s, and no failure sequence ended "
                f"in a successful login.")

    # ---- sections ---------------------------------------------------

    def masthead(self):
        stamp = self.generated_at.strftime("%d %B %Y at %H:%M")
        return f"""
        <div class="masthead">
          <div>
            <h1>SSH Brute Force Analysis</h1>
            <p class="sub">{esc(os.path.basename(str(self.result.source)))}</p>
          </div>
          <div class="sub" style="text-align:right">
            <div>{esc(stamp)}</div>
            <div class="mono">threshold {self.result.threshold} /
              {self.result.window}s</div>
          </div>
        </div>"""

    def provenance(self):
        note = PROVENANCE.get(self.source_kind, PROVENANCE["upload"])
        return f"""<div class="banner"><strong>Data source.</strong>
          {esc(note)}</div>"""

    def summary(self):
        stats = self.result.to_dict()["stats"]
        tiles = [
            ("Events parsed", stats["events"], ""),
            ("Failures", stats["failures"], ""),
            ("Successes", stats["successes"], ""),
            ("Unique sources", stats["unique_ips"], ""),
            ("Lines skipped", stats["skipped"], ""),
            ("Findings", stats["findings"], "warn" if stats["findings"] else "ok"),
            ("High severity", stats["high"], "bad" if stats["high"] else "ok"),
        ]
        cells = "".join(
            f'<div class="tile {cls}"><div class="n">{n}</div>'
            f'<div class="l">{esc(label)}</div></div>'
            for label, n, cls in tiles)
        return f'<h2>Summary</h2><div class="grid">{cells}</div>'

    def findings_table(self):
        if not self.result.findings:
            return ("<h2>Findings</h2><p>None. Every source in this log stayed "
                    "below the configured threshold.</p>")

        rows = []
        for f in self.result.findings:
            record = (self.enricher.lookup(f.key) if f.pivot == "ip" else {})
            where = Enricher.describe(record) if record else "—"
            seen = self.history.get(f.key, {}).get("times_seen", 0)
            history = (f"seen in {seen} previous analyses" if seen
                       else "first time seen")
            rows.append(f"""
              <tr>
                <td><span class="tag {esc(f.severity)}">{esc(f.severity)}</span></td>
                <td><span class="tag pivot">{esc(f.pivot)}</span></td>
                <td class="mono"><strong>{esc(f.key)}</strong><br>
                    <span class="note">{esc(where)}</span></td>
                <td>{esc(f.detail)}<br>
                    <span class="note">{esc(history)}</span></td>
              </tr>""")

        notes = "".join(
            f"<li><strong>{esc(sev)}</strong> — {esc(note)}</li>"
            for sev, note in SEVERITY_NOTE.items()
            if any(f.severity == sev for f in self.result.findings))

        return f"""<h2>Findings</h2>
          <table>
            <thead><tr><th>Severity</th><th>Grouped by</th>
              <th>Source</th><th>Evidence</th></tr></thead>
            <tbody>{''.join(rows)}</tbody>
          </table>
          <h3>What these mean</h3><ul>{notes}</ul>"""

    def suppressed_section(self):
        if not self.result.suppressed:
            return ""
        rows = "".join(
            f'<tr><td class="mono">{esc(f.key)}</td>'
            f'<td><span class="tag pivot">{esc(f.pivot)}</span></td>'
            f'<td>{esc(f.detail)}</td></tr>'
            for f in self.result.suppressed)
        entries = ", ".join(self.result.allowlist.raw) if self.result.allowlist else ""
        return f"""<h2>Suppressed by allowlist</h2>
          <p class="note">These crossed the threshold but were withheld because
            the operator listed their source as trusted
            (<span class="mono">{esc(entries)}</span>). Shown so nothing is
            hidden without a record.</p>
          <table><thead><tr><th>Source</th><th>Grouped by</th>
            <th>Evidence</th></tr></thead><tbody>{rows}</tbody></table>"""

    def timeline_section(self):
        buckets = self.result.timeline()
        if not buckets:
            return ""
        peak = max((b["failures"] for b in buckets), default=1) or 1
        bars = "".join(
            f'<div class="b{" hot" if b["failures"] >= peak * .75 and b["failures"] else ""}"'
            f' style="height:{max(b["failures"] / peak * 100, 2) if b["failures"] else 0}%"'
            f' title="{esc(b["label"])}: {b["failures"]}"></div>'
            for b in buckets)
        labelled = [b["label"] for b in buckets if b["label"]]
        first = labelled[0] if labelled else ""
        last = labelled[-1] if labelled else ""
        return f"""<h2>Failed attempts over time</h2>
          <div class="chart">{bars}</div>
          <div class="axis"><span class="mono">{esc(first)}</span>
            <span class="note">peak {peak} in one bucket</span>
            <span class="mono">{esc(last)}</span></div>"""

    def sources_section(self):
        offenders = self.result.top_offenders(limit=10)
        if not offenders:
            return ""
        flagged = {f.key for f in self.result.findings}
        peak = max((o["failures"] for o in offenders), default=1) or 1
        rows = []
        for o in offenders:
            record = self.enricher.lookup(o["ip"])
            rows.append(f"""
              <div class="bar {'flagged' if o['ip'] in flagged else ''}">
                <span class="mono" title="{esc(Enricher.describe(record))}">{esc(o['ip'])}</span>
                <span class="track"><span class="fill"
                  style="width:{o['failures'] / peak * 100:.1f}%"></span></span>
                <span class="n mono">{o['failures']}</span>
              </div>""")
        return (f"<h2>Busiest sources</h2>{''.join(rows)}"
                f'<p class="note">Red bars produced a finding. '
                f'Grey bars stayed below the threshold.</p>')

    def method_section(self):
        allow = (", ".join(self.result.allowlist.raw)
                 if self.result.allowlist and self.result.allowlist.raw
                 else "none")
        return f"""<h2>How this was produced</h2>
          <p>Each line was parsed into a structured event. Lines that are not
             authentication attempts were discarded rather than counted, and an
             rsyslog <span class="mono">message repeated N times</span> summary
             was expanded back into N attempts.</p>
          <p>Failures were then grouped four ways and checked against a sliding
             window of <strong>{self.result.threshold} failures within
             {self.result.window} seconds</strong>:</p>
          <ul>
            <li><strong>By source address</strong> — a single machine guessing.</li>
            <li><strong>By username</strong> — password spraying, or many
                machines against one account.</li>
            <li><strong>By /24 subnet</strong> — a botnet whose individual
                addresses each stay under the threshold.</li>
            <li><strong>Compromise correlation</strong> — failures that ended in
                a successful login. This one does not depend on the threshold
                at all, which is why it still fires when everything else is
                tuned too high.</li>
          </ul>
          <p class="note">Allowlisted sources: <span class="mono">{esc(allow)}</span>.
             Geo lookup: {"enabled" if self.enricher.geo_available else
             "not configured — addresses are classified from the address itself, "
             "and no location is invented."}</p>"""

    def limits_section(self):
        return """<h2>Limitations of this analysis</h2>
          <ul>
            <li>Syslog records no year, so a log spanning 31 December to
                1 January produces a negative interval and the attack is missed.</li>
            <li>Day-of-year arithmetic assumes a non-leap year: 29 February and
                1 March collapse to the same day.</li>
            <li>An rsyslog-collapsed line becomes N events sharing one
                timestamp, because the log does not record when the intermediate
                attempts happened. The burst therefore appears tighter than it
                was.</li>
            <li>Subnet grouping is IPv4 only. IPv6 addresses are reported
                individually.</li>
            <li>A threshold catches what crosses it. An attacker who stays one
                attempt below, forever, is invisible to the burst checks —
                only the compromise correlation would catch them, and only if
                they eventually succeed.</li>
          </ul>"""

    # ---- assembly ---------------------------------------------------

    def build(self):
        kind, headline, detail = self.verdict()
        title = f"SSH Brute Force Report — {os.path.basename(str(self.result.source))}"
        return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{esc(title)}</title><style>{CSS}</style></head>
<body><div class="page">
{self.masthead()}
{self.provenance()}
<div class="verdict {kind}"><strong>{esc(headline)}</strong>{esc(detail)}</div>
{self.summary()}
{self.findings_table()}
{self.suppressed_section()}
{self.timeline_section()}
{self.sources_section()}
{self.method_section()}
{self.limits_section()}
<footer>Generated by Brute Force Log Analyzer v{esc(self.tool_version)} on
{esc(self.generated_at.strftime('%d %B %Y at %H:%M:%S'))}.
This file is self-contained — no network access is required to view it.</footer>
</div></body></html>"""


def build_report(result, **kwargs):
    return ReportBuilder(result, **kwargs).build()
