@app.route("/api/live/start", methods=["POST"])
def live_start():
    global watcher

    form = request.get_json(silent=True) or {}
    path = (form.get("path") or config.watch_path or "").strip()
    if not path:
        return jsonify({
            "error": "No log path to follow.",
            "hint": "Set BFLA_WATCH_PATH, or pass {\"path\": \"...\"}. "
                    "On Linux this is usually /var/log/auth.log.",
        }), 400

    if watcher and watcher.running:
        watcher.stop()

    watcher = LiveWatcher(
        path,
        detector=detector_from(form),
        retention_seconds=config.watch_retention_seconds,
        poll_seconds=config.watch_poll_seconds,
        storage=storage, dispatcher=dispatcher, enricher=enricher)
    watcher.start(from_end=bool(form.get("from_end", True)))
    return jsonify(watcher.status())


